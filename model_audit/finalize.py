"""Verify the audited production identity and freeze compact audit file hashes."""
import datetime
import hashlib
import json
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    provenance = json.loads((HERE/'provenance.json').read_text(encoding='utf-8'))
    for item in provenance['implementation']+provenance['additional_files']:
        assert sha(Path(item['path'])) == item['sha256'], item['path']
    assert '100% tests passed, 0 tests failed out of 4' in (HERE/'ctest.log').read_text(encoding='utf-8-sig')
    for path in [HERE/'README_RU.md', HERE/'neurons/README.md',
                 HERE/'synapses/README.md', HERE/'astrocytes/README_RU.md',
                 HERE/'integration/README_RU.md']:
        assert path.is_file(), path
        for target in re.findall(r'\]\(([^)]+)\)', path.read_text(encoding='utf-8')):
            if '://' in target or target.startswith('#'):
                continue
            file = (path.parent/target.split('#')[0]).resolve()
            if file == HERE/'manifest.json':
                continue
            assert file.exists(), (path, target)
    entries = []
    exclude = {'raw', 'runs', 'results', 'build', '__pycache__'}
    suffixes = {'.md', '.json', '.py', '.ps1', '.cpp', '.txt', '.csv', '.log'}
    for path in sorted(HERE.rglob('*')):
        relative = path.relative_to(HERE)
        if not path.is_file() or path == HERE/'manifest.json':
            continue
        if set(relative.parts[:-1]) & exclude or (path.suffix not in suffixes and path.name != '.gitignore'):
            continue
        entries.append({'path': relative.as_posix(), 'bytes': path.stat().st_size, 'sha256': sha(path)})
    manifest = {'created_utc': datetime.datetime.now(datetime.timezone.utc).isoformat(),
                'production_unchanged_since_audit_start': True,
                'production_checks': len(provenance['implementation'])+len(provenance['additional_files']),
                'entries': entries,
                'note': 'Compact documentation, source and result hashes. Raw runs and diagnostic binaries remain local and are regenerated by the scripts.'}
    (HERE/'manifest.json').write_text(json.dumps(manifest, indent=2)+'\n', encoding='utf-8')
    print(json.dumps({'production_identity': 'unchanged', 'compact_files': len(entries),
                      'bytes': sum(x['bytes'] for x in entries)}))


if __name__ == '__main__':
    main()
