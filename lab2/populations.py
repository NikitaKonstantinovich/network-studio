def base_config(seed=42, duration=100., dt=.000025, noise=3.):
    value = json.loads((STUDIO / "examples" / "stdp_manual.json").read_text(encoding="utf-8"))
    value.update(name=f"Lab 2 / homogeneous population / seed {seed}", duration=duration,
                 dt=dt, sample=.01, noise_sigma=noise, noise_interval=.001, seed=seed)
    value["neurons"] = [value["neurons"][0]]
    value["neurons"][0].update(name="RS template", amplitude=0., current=0., start=.1,
                                stop=duration, frequency=0., individual_noise=False)
    value["synapses"][0].update(source=0, target=0, model="tsodyks_markram", gain=20.,
                                weight=1., release=.5, tau_syn=.01, tau_d=.05,
                                tau_f=1., stdp=False, spill=0., astro=-1)
    return value


def graph(seed, degree_mean, degree_sd, topology="uniform"):
    # Independent RNG streams keep degree draws, edge selection, weights and
    # spatial coordinates separate. Noise is generated by the native core.
    streams = np.random.SeedSequence(seed).spawn(4)
    degree_rng, edge_rng, weight_rng, coordinate_rng = [np.random.default_rng(s) for s in streams]
    degree = np.clip(np.rint(degree_rng.normal(degree_mean, degree_sd, 500)), 0, 499).astype(int)
    positions = coordinate_rng.uniform(0., 1200., (500, 2))
    edges = []
    rejected = 0
    for target, k in enumerate(degree):
        candidates = np.delete(np.arange(500), target)
        if topology == "uniform":
            sources = edge_rng.choice(candidates, int(k), replace=False)
        elif topology == "nearest":
            distances = np.sum((positions[candidates] - positions[target]) ** 2, axis=1)
            sources = candidates[np.argsort(distances, kind="stable")[:k]]
        else:
            raise ValueError(topology)
        for source in sources:
            magnitude = float(weight_rng.normal(.5, .1))
            while not 0. <= magnitude <= 1.:
                rejected += 1
                magnitude = float(weight_rng.normal(.5, .1))
            edges.append((int(source), target, magnitude if source < 400 else -magnitude))
    magnitudes = np.abs([e[2] for e in edges])
    return edges, dict(seed=seed, topology=topology, neurons=500, excitatory_neurons=400,
        inhibitory_neurons=100, synapses=len(edges), indegree_requested_mean=degree_mean,
        indegree_requested_sd=degree_sd, indegree_mean=float(np.mean(degree)),
        indegree_sd=float(np.std(degree, ddof=1)), indegree_min=int(min(degree)),
        indegree_max=int(max(degree)), magnitude_mean=float(np.mean(magnitudes)),
        magnitude_sd=float(np.std(magnitudes, ddof=1)), rejected_weight_draws=rejected,
        excitatory_edges=sum(s < 400 for s, _, _ in edges),
        inhibitory_edges=sum(s >= 400 for s, _, _ in edges),
        self_edges=0, duplicate_edges=0)


def prepare():
    CONFIGS.mkdir(parents=True, exist_ok=True)
    scenarios, graphs = {}, {}
    for seed in [11, 42, 101]:
        for mean, sd in [(15, 2), (30, 3)]:
            key = f"k{mean:02}_seed{seed}"
            edges, info = graph(seed, mean, sd)
            graphs[key] = info
            with (CONFIGS / f"{key}_edges.csv").open("w", newline="", encoding="utf-8") as stream:
                writer = csv.writer(stream)
                writer.writerow(["source", "target", "weight"])
                writer.writerows(edges)
            duration = 100. if seed == 42 else 30.
            scenarios[key] = dict(base=base_config(seed, duration), graph=key, role="main")
    # Spatial locality is not defined sufficiently in the source wizard. This
    # explicitly defined nearest-neighbor graph is a sensitivity check only.
    for mean, sd in [(15, 2), (30, 3)]:
        key = f"k{mean:02}_seed42_nearest"
        edges, graphs[key] = graph(42, mean, sd, "nearest")
        with (CONFIGS / f"{key}_edges.csv").open("w", newline="", encoding="utf-8") as stream:
            writer = csv.writer(stream)
            writer.writerow(["source", "target", "weight"])
            writer.writerows(edges)
        scenarios[key] = dict(base=base_config(42, 30.), graph=key, role="topology_control")
    for mean in [15, 30]:
        key = f"k{mean:02}_seed42"
        scenarios[key + "_short"] = dict(base=base_config(42, 10.), graph=key, role="step_control")
        scenarios[key + "_fine"] = dict(base=base_config(42, 10., .0000125), graph=key, role="step_control")
        scenarios[key + "_quiet"] = dict(base=base_config(42, 10., noise=0.), graph=key, role="zero_noise_control")
    scenarios["k30_seed42_repeat"] = copy.deepcopy(scenarios["k30_seed42_short"])
    scenarios["k30_seed42_repeat"]["role"] = "replay"
    for name, value in scenarios.items():
        value["base"]["name"] = f"Lab 2 / {name}"
        if name == "k30_seed42_repeat":
            value["base"] = copy.deepcopy(scenarios["k30_seed42_short"]["base"])
        write_json(CONFIGS / f"{name}_base.json", value["base"])
    write_json(RESULTS / "graphs.json", graphs)
    write_json(RESULTS / "manifest.json", dict(source_pdf_sha256=SOURCE_SHA256,
        source_pages=[17, 18, 19, 20, 21, 22], scenarios={k: dict(graph=v["graph"], role=v["role"])
        for k, v in scenarios.items()}, protocol=dict(neurons=500, excitatory=400, inhibitory=100,
        graph="uniform sources without replacement, excluding self edges; fixed source sign",
        degree="rounded Gaussian, clipped to [0,499]", weight="Gaussian magnitude .5 +/-.1, rejection outside [0,1]",
        noise="native Gaussian sample-and-hold current, sigma=3, interval=1 ms",
        dynamics="RS Izhikevich and Tsodyks-Markram; STDP off; no axonal delays",
        burst_detector="local maxima of 50-ms population rate strictly above 5 Hz, plateau center, 50-ms minimum peak separation; height priority, earlier ties",
        topology_control="k nearest Euclidean neighbors of uniform points in [0,1200]^2; not an emulation of the undocumented wizard")))
    return scenarios, graphs


def execute(exe, scenarios, selected):
    RAW.mkdir(parents=True, exist_ok=True)
    exe_hash = digest(exe)
    provenance_path = RESULTS / "run_provenance.json"
    provenance = json.loads(provenance_path.read_text(encoding="utf-8")) if provenance_path.exists() else {}
    for name in selected:
        spec = scenarios[name]
        base = CONFIGS / f"{name}_base.json"
        edges = CONFIGS / f"{spec['graph']}_edges.csv"
        command = [str(exe), "--base", str(base), "--edges", str(edges), "--neurons", "500", "--output", str(RAW / name)]
        print(f"RUN {name}: {spec['base']['duration']:g} s", flush=True)
        started = time.perf_counter()
        completed = subprocess.run(command, capture_output=True, text=True, encoding="utf-8", errors="replace")
        (RAW / f"{name}_cli.log").write_text(completed.stdout + completed.stderr, encoding="utf-8")
        if completed.returncode:
            raise RuntimeError(f"{name}: {completed.stderr or completed.stdout}")
        if digest(exe) != exe_hash:
            raise RuntimeError("Population executable changed during the run.")
        provenance[name] = dict(executable_sha256=exe_hash, base_sha256=digest(base), edges_sha256=digest(edges),
            wall_seconds=round(time.perf_counter() - started, 3), command=command,
            outputs={suffix: digest(RAW / f"{name}_{suffix}") for suffix in ["events.csv", "trace.csv", "summary.json", "base.json"]})
        write_json(provenance_path, provenance)


def events(name):
    times, nodes = [], []
    with (RAW / f"{name}_events.csv").open(encoding="utf-8") as stream:
        reader = csv.DictReader(stream)
        if reader.fieldnames != ["time_s", "type", "node_index_1based"]:
            raise AssertionError("Unexpected event columns")
        for row in reader:
            assert row["type"] == "spike"
            times.append(float(row["time_s"]))
            nodes.append(int(row["node_index_1based"]))
    return np.asarray(times, dtype=float), np.asarray(nodes, dtype=int)


def selected_peaks(rates, distance_ms):
    candidates, _ = find_peaks(rates, height=np.nextafter(5., np.inf))
    blocked = np.zeros(len(rates), dtype=bool)
    selected = []
    for peak in sorted(candidates, key=lambda p: (-rates[p], p)):
        if not blocked[peak]:
            selected.append(int(peak))
            blocked[max(0, peak - distance_ms + 1):peak + distance_ms] = True
    return np.asarray(sorted(selected), dtype=int)


def population_curves(times, duration):
    ticks = np.arange(round(duration * 1000) + 1) / 1000.
    right = np.searchsorted(times, ticks + 1e-12, side="right")
    left = np.searchsorted(times, ticks - .05 + 1e-12, side="right")
    rates = (right - left) / (500 * .05)
    peaks = selected_peaks(rates, 50)
    burst_times = ticks[peaks]
    burst_rate = (np.searchsorted(burst_times, ticks + 1e-12, side="right") -
                  np.searchsorted(burst_times, ticks - 5. + 1e-12, side="right")) / 5.
    local, _ = find_peaks(rates, height=np.nextafter(5., np.inf))
    return ticks, rates, burst_rate, burst_times, ticks[local]


def analyze(scenarios, selected):
    provenance = json.loads((RESULTS / "run_provenance.json").read_text(encoding="utf-8"))
    metrics = {}
    for name in selected:
        spec = scenarios[name]
        base = spec["base"]
        p = provenance[name]
        assert digest(CONFIGS / f"{name}_base.json") == p["base_sha256"]
        assert digest(CONFIGS / f"{spec['graph']}_edges.csv") == p["edges_sha256"]
        for suffix, expected_hash in p["outputs"].items():
            assert digest(RAW / f"{name}_{suffix}") == expected_hash
        snapshot = json.loads((RAW / f"{name}_base.json").read_text(encoding="utf-8"))
        assert canonical_config(snapshot) == canonical_config(base), f"{name}: exported base differs"
        summary = json.loads((RAW / f"{name}_summary.json").read_text(encoding="utf-8"))
        assert summary["complete"] and not summary["error"]
        assert abs(summary["time_s"] - base["duration"]) < 1e-10
        times, nodes = events(name)
        assert np.all(np.isfinite(times)) and np.all(np.diff(times) >= 0)
        assert np.all((times > 0) & (times <= base["duration"]))
        assert np.all((nodes >= 1) & (nodes <= 500))
        counts = np.bincount(nodes, minlength=501)[1:]
        assert counts.tolist() == summary["neuron_spikes"]
        trace = np.genfromtxt(RAW / f"{name}_trace.csv", delimiter=",", names=True)
        assert np.all(np.isfinite(np.column_stack([trace[k] for k in trace.dtype.names])))
        assert np.all(np.diff(trace["time_s"]) > 0)
        assert abs(trace["time_s"][-1] - base["duration"]) < 1e-10
        ticks, rates, burst_rate, burst_times, local_times = population_curves(times, base["duration"])
        keep = times > 5.
        span = base["duration"] - 5.
        comparison_end = min(30., base["duration"])
        comparison_span = comparison_end - 5.
        above = rates > 5.
        crossings = np.diff(np.r_[False, above, False].astype(int))
        starts, stops = np.flatnonzero(crossings == 1), np.flatnonzero(crossings == -1)
        excursion_maxima = np.asarray([a + int(np.argmax(rates[a:b])) for a, b in zip(starts, stops)], dtype=int)
        metrics[name] = dict(duration_s=base["duration"], spikes=int(len(times)),
            active_neurons=int(np.sum(counts > 0)), mean_rate_hz=float(np.sum(keep) / (500 * span)),
            excitatory_rate_hz=float(np.sum(keep & (nodes <= 400)) / (400 * span)),
            inhibitory_rate_hz=float(np.sum(keep & (nodes > 400)) / (100 * span)),
            max_population_rate_hz=float(max(rates)), population_rate_sd_hz=float(np.std(rates[ticks > 5.])),
            bursts=int(len(burst_times)), burst_rate_hz=float(np.sum(burst_times > 5.) / span),
            local_peak_rate_hz=float(np.sum(local_times > 5.) / span),
            burst_rate_distance25_hz=float(np.sum(ticks[selected_peaks(rates, 25)] > 5.) / span),
            burst_rate_distance100_hz=float(np.sum(ticks[selected_peaks(rates, 100)] > 5.) / span),
            excursion_burst_rate_hz=float(np.sum(ticks[excursion_maxima] > 5.) / span),
            comparison_window_s=[5., comparison_end],
            comparison_mean_rate_hz=float(np.sum(keep & (times <= comparison_end)) / (500 * comparison_span)),
            comparison_burst_rate_hz=float(np.sum((burst_times > 5.) & (burst_times <= comparison_end)) / comparison_span),
            late_window_s=[5., base["duration"]], role=spec["role"], checks_passed=True)
        if spec["role"] == "zero_noise_control":
            assert len(times) == 0, "The undriven network should stay quiet"
        np.savetxt(RESULTS / f"{name}_characteristics.csv", np.column_stack([ticks, rates, burst_rate]),
                   delimiter=",", header="time_s,population_rate_50ms_hz,burst_rate_5s_hz", comments="", fmt="%.8g")
    checks = {}
    if {"k30_seed42_repeat", "k30_seed42_short"} <= metrics.keys():
        checks["repeat_csv_byte_identical"] = all(digest(RAW / f"k30_seed42_repeat_{s}.csv") ==
            digest(RAW / f"k30_seed42_short_{s}.csv") for s in ["trace", "events"])
        assert checks["repeat_csv_byte_identical"]
    for mean in [15, 30]:
        a, b = f"k{mean:02}_seed42_short", f"k{mean:02}_seed42_fine"
        if a in metrics and b in metrics:
            ta, na = events(a)
            tb, nb = events(b)
            differences = []
            matched = True
            for node in range(1, 501):
                x, y = ta[na == node], tb[nb == node]
                matched &= len(x) == len(y)
                if len(x) == len(y) and len(x):
                    differences.extend(np.abs(x - y).tolist())
            checks[f"k{mean:02}_step_halving"] = dict(counts_equal_per_neuron=bool(matched),
                spikes_coarse=len(ta), spikes_fine=len(tb),
                max_matched_ordinal_event_difference_ms=float(max(differences) * 1000.) if matched and differences else None,
                mean_rate_coarse_hz=metrics[a]["mean_rate_hz"], mean_rate_fine_hz=metrics[b]["mean_rate_hz"],
                burst_rate_coarse_hz=metrics[a]["burst_rate_hz"], burst_rate_fine_hz=metrics[b]["burst_rate_hz"])
    write_json(RESULTS / "metrics.json", dict(runs=metrics, checks=checks))
    return metrics


def plots(metrics, graphs):
    FIGURES.mkdir(parents=True, exist_ok=True)
    plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 10, "axes.spines.top": False,
                         "axes.spines.right": False, "figure.dpi": 140})
    if all(f"k{k:02}_seed42" in metrics for k in [15, 30]):
        fig, axes = plt.subplots(3, 2, figsize=(12, 8), constrained_layout=True)
        for col, mean in enumerate([15, 30]):
            name = f"k{mean:02}_seed42"
            times, nodes = events(name)
            ticks, rates, bursts, _, _ = population_curves(times, metrics[name]["duration_s"])
            selected = (times >= 5.) & (times <= 15.)
            axes[0, col].scatter(times[selected], nodes[selected], s=.3, c=np.where(nodes[selected] <= 400, "#2878b5", "#bf4b45"), rasterized=True)
            axes[0, col].set(xlim=(5, 15), ylim=(0, 501), ylabel="Номер нейрона", title=f"Входная степень {mean} ± {2 if mean == 15 else 3}")
            axes[0, col].axhline(400.5, color="gray", lw=.7)
            axes[1, col].plot(ticks, rates, lw=.8, color="#2878b5")
            axes[1, col].axhline(5, color="#bf4b45", ls="--", lw=.8, label="Порог 5 Гц")
            axes[1, col].set(xlim=(5, 15), ylabel="Средняя частота, Гц", xlabel="Время, с")
            axes[1, col].legend(loc="upper right", fontsize=8)
            axes[2, col].plot(ticks, bursts, color="#26846a", lw=.9)
            axes[2, col].set(xlim=(0, 100), ylabel="Частота пачек, Гц", xlabel="Время, с")
        for row in [1, 2]:
            upper = max(axis.get_ylim()[1] for axis in axes[row])
            for axis in axes[row]:
                axis.set_ylim(0., upper)
        fig.suptitle("500 RS-нейронов · 400 возбуждающих / 100 тормозных\nTM, STDP выключена, шум σ=3, seed=42", fontsize=13)
        fig.savefig(FIGURES / "populations_activity.png")
        plt.close(fig)
        fig, axes = plt.subplots(2, 2, figsize=(10, 6), constrained_layout=True)
        for col, mean in enumerate([15, 30]):
            key = f"k{mean:02}_seed42"
            data = np.genfromtxt(CONFIGS / f"{key}_edges.csv", delimiter=",", names=True)
            weights = np.abs(data["weight"])
            degree = np.bincount(data["target"].astype(int), minlength=500)
            axes[0, col].hist(degree, bins=np.arange(min(degree) - .5, max(degree) + 1.5), color="#2878b5", alpha=.8)
            axes[0, col].set(title=f"Связность {mean} ± {2 if mean == 15 else 3}", xlabel="Число входящих связей", ylabel="Нейронов")
            axes[1, col].hist(weights, bins=35, density=True, color="#26846a", alpha=.65, label="Заданные веса")
            x = np.linspace(0, 1, 500)
            axes[1, col].plot(x, np.exp(-.5 * ((x - .5) / .1) ** 2) / (.1 * np.sqrt(2 * np.pi)), color="#303740", label="N(0.5, 0.1²)")
            info = graphs[key]
            axes[1, col].set(xlabel="Модуль веса |w|", ylabel="Плотность", title=f"{info['synapses']} связей; |w| = {info['magnitude_mean']:.4f} ± {info['magnitude_sd']:.4f}")
            axes[1, col].legend(fontsize=8)
        fig.savefig(FIGURES / "populations_distributions.png")
        plt.close(fig)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--exe", type=Path, default=STUDIO / "build/Release/network_studio_population.exe")
    parser.add_argument("--python-deps", type=Path)
    parser.add_argument("--prepare-only", action="store_true")
    parser.add_argument("--skip-run", action="store_true")
    parser.add_argument("--only", nargs="+", help="Selected names from manifest.json")
    args = parser.parse_args()
    imports(args.python_deps)
    scenarios, graphs = prepare()
    selected = args.only or list(scenarios)
    assert all(name in scenarios for name in selected)
    if args.prepare_only:
        print(f"Prepared {len(scenarios)} population scenarios")
        return
    if not args.skip_run:
        execute(args.exe.resolve(), scenarios, selected)
    metrics = analyze(scenarios, selected)
    plots(metrics, graphs)
    source_files = [HERE / "populations.py", HERE / "population.cpp", HERE / "population.h",
                    STUDIO / "network.cpp", STUDIO / "network.h", STUDIO / "io.cpp"]
    write_json(RESULTS / "analysis_provenance.json", dict(python=sys.version, numpy=np.__version__,
        scipy=__import__("scipy").__version__, matplotlib=__import__("matplotlib").__version__,
        source_sha256_at_analysis={str(p.relative_to(STUDIO)): digest(p) for p in source_files},
        source_pdf_sha256=SOURCE_SHA256, selected=selected))
    print(json.dumps(metrics, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
